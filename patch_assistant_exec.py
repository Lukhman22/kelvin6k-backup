with open('agent/assistant.py', 'r') as f:
    lines = f.readlines()

out = []
skip = False
for i, line in enumerate(lines):
    if line.startswith('        if action.intent == "SHIFT_START":'):
        skip = True
        out.append('        if action.intent == "SHIFT_START":\n')
        out.append('            operator_id = action.params.get("operator_id")\n')
        out.append('            op_name = action.params.get("operator_name", "Operator")\n')
        out.append('            if action.params.get("create_operator"):\n')
        out.append('                clean_code = re.sub(r"[^A-Za-z0-9]", "", op_name).upper()\n')
        out.append('                new_op_id = f"OP_{clean_code}"\n')
        out.append('                if shift_store.get_operator(new_op_id):\n')
        out.append('                    idx = 1\n')
        out.append('                    while shift_store.get_operator(f"{new_op_id}_{idx}"):\n')
        out.append('                        idx += 1\n')
        out.append('                    new_op_id = f"{new_op_id}_{idx}"\n')
        out.append('                shift_store.create_operator(\n')
        out.append('                    operator_id=new_op_id,\n')
        out.append('                    name=op_name,\n')
        out.append('                    role="operator",\n')
        out.append('                    active=1,\n')
        out.append('                )\n')
        out.append('                operator_id = new_op_id\n')
        out.append('                action.params["operator_id"] = new_op_id\n')
        out.append('\n')
        out.append('            started_at = self._server_now()\n')
        out.append('            moment = datetime.datetime.fromtimestamp(started_at)\n')
        out.append('            shift_date = moment.date().isoformat()\n')
        out.append('            try:\n')
        out.append('                record_id = shift_store.create_attendance_record(\n')
        out.append('                    operator_id=operator_id,\n')
        out.append('                    employee_name=op_name,\n')
        out.append('                    attendance_date=shift_date\n')
        out.append('                )\n')
        out.append('                self._session_ctx.update(\n')
        out.append('                    action.session_id,\n')
        out.append('                    line_id,\n')
        out.append('                    current_operator_id=operator_id,\n')
        out.append('                    current_operator_name=op_name,\n')
        out.append('                )\n')
        out.append('                return f"{op_name}, your shift has started."\n')
        out.append('            except Exception as exc:\n')
        out.append('                log.error("Failed to start attendance shift: %s", exc)\n')
        out.append('                return f"Failed to start shift: {exc}"\n')
        out.append('\n')
        out.append('        if action.intent == "SHIFT_END":\n')
        out.append('            operator_id = action.params.get("operator_id")\n')
        out.append('            op_name = action.params.get("operator_name", "Operator")\n')
        out.append('            try:\n')
        out.append('                records = shift_store.list_attendance_records()\n')
        out.append('                active = None\n')
        out.append('                for r in records:\n')
        out.append('                    if r["status"] == "ACTIVE" and (r["operator_id"] == operator_id or (not operator_id and r["employee_name"] == op_name)):\n')
        out.append('                        active = r\n')
        out.append('                        break\n')
        out.append('                if not active:\n')
        out.append('                    return f"No active shift found for {op_name}."\n')
        out.append('                shift_store.checkout_attendance_record(\n')
        out.append('                    record_id=active["id"],\n')
        out.append('                    operator_id=operator_id,\n')
        out.append('                    employee_name=op_name\n')
        out.append('                )\n')
        out.append('                fmt = "%Y-%m-%d %H:%M:%S"\n')
        out.append('                start_dt = datetime.datetime.strptime(active["shift_start"], fmt)\n')
        out.append('                end_dt = datetime.datetime.now()\n')
        out.append('                diff = end_dt - start_dt\n')
        out.append('                hours = int(diff.total_seconds() // 3600)\n')
        out.append('                minutes = int((diff.total_seconds() % 3600) // 60)\n')
        out.append('                dur_str = f" {hours} hours {minutes} minutes" if hours > 0 else f" {minutes} minutes"\n')
        out.append('                self._session_ctx.clear(action.session_id, line_id)\n')
        out.append('                return f"{op_name}, your shift has ended. Duration:{dur_str}."\n')
        out.append('            except Exception as exc:\n')
        out.append('                log.error("Failed to end attendance shift: %s", exc)\n')
        out.append('                return f"Failed to end shift: {exc}"\n')
        continue
    
    if skip and line.startswith('        if action.intent == "LOG_WALL_PRODUCTION":'):
        skip = False
    
    if not skip:
        out.append(line)

with open('agent/assistant.py', 'w') as f:
    f.writelines(out)
